<?php

namespace App\ML;

/**
 * Преобразование сырых величин маршрута в признаки модели.
 *
 * Дистанции в датасете растягиваются на 3 порядка (от долей км до ~1500 км).
 * Линейный признак distance/1000 сжимает всю "пешеходную" зону (0–3 км) в
 * практически неразличимую точку рядом с началом координат — на глаз это
 * 0.003 против, например, 0.35 для 350 км. Линейному классификатору такой
 * узкий диапазон почти невозможно отделить от соседнего класса.
 *
 * Логарифмическое масштабирование (log1p) решает эту проблему: короткие
 * расстояния получают гораздо больше "пространства" в признаковом
 * пространстве, а разница между 1 км и 3 км становится сопоставима по
 * значимости с разницей между 300 км и 900 км — что как раз отражает, как
 * люди воспринимают расстояния на практике.
 */
class FeatureEncoder
{
    private const MAX_EXPECTED_KM = 1500.0;

    public static function distanceFeature(float $distanceKm): float
    {
        return log(1 + $distanceKm) / log(1 + self::MAX_EXPECTED_KM);
    }

    public static function stopsFeature(int $stopsCount): float
    {
        return $stopsCount / 10;
    }
}
