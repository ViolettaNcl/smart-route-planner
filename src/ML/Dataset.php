<?php

namespace App\ML;

/**
 * Генератор обучающих данных для классификатора транспорта.
 *
 * У нас нет реального лога решений пользователей (приложение не хранит
 * историю), поэтому датасет — синтетический: признаки (дистанция, число
 * точек) генерируются случайно в реалистичных диапазонах, а метка класса
 * проставляется по понятному человеку правилу с добавлением шума. Шум нужен
 * специально: без него классы отделяются идеальной границей, и обучение
 * жёсткого классификатора вырождается в тривиальную задачу, а веса модели
 * уходят в бесконечность. Небольшой процент "нетипичных" меток имитирует
 * реальные человеческие решения (кто-то поедет 4 км на машине просто потому
 * что жарко) и даёт модели данные, на которых видна разница между обучением
 * и подгонкой констант вручную.
 *
 * Честно предупреждаем: это учебный датасет, а не собранная статистика
 * реальных пользователей — см. docs/neural_net.md.
 */
class Dataset
{
    public const CLASSES = ['walk', 'car', 'bus'];

    public function __construct(private int $seed = 42)
    {
    }

    /**
     * @return array<int, array{distance: float, stops: int, label: string}>
     */
    public function generate(int $samples = 500): array
    {
        mt_srand($this->seed);

        $rows = [];

        for ($i = 0; $i < $samples; $i++) {
            $distance = $this->randomDistance();
            $stops = mt_rand(2, 12);
            $label = $this->groundTruthLabel($distance, $stops);

            $rows[] = ['distance' => $distance, 'stops' => $stops, 'label' => $label];
        }

        return $rows;
    }

    private function randomDistance(): float
    {
        // Смесь коротких, средних и дальних маршрутов, а не равномерное
        // распределение — так датасет больше похож на реальные поездки.
        // Диапазон 0–30 км разбит на два отдельных бакета: без этого короткие
        // прогулочные расстояния (0–3 км, класс "walk") составляли только
        // ~10% от городского бакета и ~5% от всего датасета — классического
        // дисбаланса классов достаточно, чтобы модель перестала уверенно
        // предсказывать "пешком" даже для однозначно коротких маршрутов.
        $bucket = mt_rand(1, 100);

        return match (true) {
            $bucket <= 20 => mt_rand(0, 300) / 100,        // 0–3 км, пешком
            $bucket <= 40 => mt_rand(300, 3000) / 100,     // 3–30 км, город/авто
            $bucket <= 80 => mt_rand(3000, 35000) / 100,   // 30–350 км, авто
            default => mt_rand(35000, 150000) / 100,       // 350–1500 км, межгород
        };
    }

    private function groundTruthLabel(float $distance, int $stops): string
    {
        $base = match (true) {
            $distance <= 3.0 => 'walk',
            $distance <= 350.0 => 'car',
            default => 'bus',
        };

        // Много точек на среднем маршруте — больше похоже на тур с
        // общественным транспортом/автобусом, чем на одиночную поездку на машине.
        if ($base === 'car' && $stops >= 8 && $distance > 100) {
            $base = 'bus';
        }

        // 8% шанс "нетипичного" решения — имитация реальной непредсказуемости людей.
        if (mt_rand(1, 100) <= 8) {
            $classes = self::CLASSES;
            $base = $classes[array_rand($classes)];
        }

        return $base;
    }
}
